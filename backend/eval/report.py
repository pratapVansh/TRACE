"""Side-by-side comparison of every config that has results.

    python -m eval.run report   ->  eval/results/comparison.md

Generated purely from the JSON results; no numbers are typed by hand.
"""

import json
from pathlib import Path

ORDER = [
    "baseline", "rerank_off", "graph_off", "chunk512", "graph_v2",
    "passage2", "passage2_graphv2", "passage2_ctx25", "graph_provenance",
]


def _load(results_dir: Path, kind: str) -> dict[str, dict]:
    found = {}
    for name in ORDER:
        path = results_dir / name / f"{kind}.json"
        if path.exists():
            found[name] = json.loads(path.read_text(encoding="utf-8"))
    return found


def _pct(value) -> str:
    return "—" if value is None else f"{value * 100:.1f}%"


def _delta(value, base) -> str:
    if value is None or base is None:
        return ""
    diff = (value - base) * 100
    return "" if abs(diff) < 0.05 else f" ({diff:+.1f})"


def _table(runs: dict[str, dict], rows: list[tuple[str, callable, str]]) -> list[str]:
    names = list(runs)
    lines = ["| Metric | " + " | ".join(names) + " |", "| --- |" + " ---: |" * len(names)]
    base = runs.get("baseline")
    for label, getter, fmt in rows:
        cells = []
        for name in names:
            value = getter(runs[name])
            if fmt == "pct":
                cells.append(_pct(value) + (_delta(value, getter(base)) if base and name != "baseline" else ""))
            elif fmt == "ms":
                cells.append("—" if value is None else f"{value:.0f}")
            else:
                cells.append("—" if value is None else f"{value:.3f}")
        lines.append(f"| {label} | " + " | ".join(cells) + " |")
    return lines


def write_comparison(results_dir: Path) -> Path:
    retrieval = _load(results_dir, "retrieval")
    answers = _load(results_dir, "answers")
    lines = ["# Stage 5 evaluation — comparison", "",
             "Generated by `python -m eval.run report` from eval/results/*/. "
             "Percentage-point change against baseline in brackets.", ""]

    if retrieval:
        a = lambda key: (lambda r: r["summary"]["answerable"][key])
        t = lambda typ, key: (lambda r: r["summary"]["by_type"][typ][key])
        g = lambda tag, key: (lambda r: r["summary"]["by_tag"].get(tag, {}).get(key))
        lines += ["## Retrieval (deterministic)", ""]
        lines += _table(retrieval, [
            ("Doc recall@5 (35 answerable)", a("doc_recall_at_5"), "pct"),
            ("Doc hit@5", a("doc_hit_rate_at_5"), "pct"),
            ("Passage recall@5", a("passage_recall_at_5"), "pct"),
            ("Evidence in LLM context", a("evidence_in_context"), "pct"),
            ("MRR", a("mrr"), "num"),
            ("Passage recall@5 — single_hop", t("single_hop", "passage_recall_at_5"), "pct"),
            ("Passage recall@5 — multi_hop", t("multi_hop", "passage_recall_at_5"), "pct"),
            ("Passage recall@5 — follow_up", t("follow_up", "passage_recall_at_5"), "pct"),
            ("Doc recall@5 — multi_hop", t("multi_hop", "doc_recall_at_5"), "pct"),
            ("Passage recall@5 — table_row", g("table_row", "passage_recall_at_5"), "pct"),
            ("Passage recall@5 — long_doc", g("long_doc", "passage_recall_at_5"), "pct"),
            ("Passage recall@5 — compound", g("compound", "passage_recall_at_5"), "pct"),
            ("Passage recall@5 — no_lexical_overlap", g("no_lexical_overlap", "passage_recall_at_5"), "pct"),
            ("Follow-up resolution", lambda r: r["summary"]["follow_up_resolution_rate"], "pct"),
            ("Top score, negatives (mean)", lambda r: r["summary"]["negative_top_score_mean"], "num"),
            ("Top score, answerable (mean)", lambda r: r["summary"]["answerable_top_score_mean"], "num"),
            ("Retrieval latency p50 (ms)", lambda r: r["summary"]["latency_ms_p50"], "ms"),
            ("Retrieval latency p95 (ms)", lambda r: r["summary"]["latency_ms_p95"], "ms"),
        ])
        lines += ["", "### Per item — passage recall@5", "",
                  "| Id | Type | " + " | ".join(retrieval) + " |", "| --- | --- |" + " ---: |" * len(retrieval)]
        first = next(iter(retrieval.values()))
        by_id = {name: {i["id"]: i for i in run["items"]} for name, run in retrieval.items()}
        for item in first["items"]:
            if item["type"] == "negative":
                continue
            cells = [_pct(by_id[name].get(item["id"], {}).get("passage_recall_at_5")) for name in retrieval]
            lines.append(f"| {item['id']} | {item['type']} | " + " | ".join(cells) + " |")

    complete = {name: run for name, run in answers.items() if not run.get("skipped_uncached")}
    if complete:
        a = lambda key: (lambda r: r["summary"]["answerable"][key])
        t = lambda typ, key: (lambda r: r["summary"]["by_type"][typ][key])
        lines += ["", "## Answers (LLM — reported, not gated)", "",
                  "Complete runs only (all 40 items). Partial runs are compared on a matched subset below.", ""]
        lines += _table(complete, [
            ("Fact coverage (35 answerable)", a("fact_coverage"), "pct"),
            ("Fully correct (all facts)", a("fully_correct_rate"), "pct"),
            ("Fact coverage — single_hop", t("single_hop", "fact_coverage"), "pct"),
            ("Fact coverage — multi_hop", t("multi_hop", "fact_coverage"), "pct"),
            ("Fact coverage — follow_up", t("follow_up", "fact_coverage"), "pct"),
            ("Correct refusal (5 negatives)", lambda r: r["summary"]["correct_refusal_rate"], "pct"),
            ("False refusal (answerable)", a("false_refusal_rate"), "pct"),
            ("Citation precision", a("citation_precision"), "pct"),
            ("Citation recall", a("citation_recall"), "pct"),
            ("Grounded sentence share", a("grounded_share"), "pct"),
            ("LLM latency p50, uncached (ms)", lambda r: r["summary"]["llm_ms_p50_uncached"], "ms"),
            ("LLM latency p95, uncached (ms)", lambda r: r["summary"]["llm_ms_p95_uncached"], "ms"),
        ])

    partial = {name: run for name, run in answers.items() if run.get("skipped_uncached")}
    if answers and partial:
        from eval.run import summarize_answers

        # A config with no answers at all would empty the intersection and turn
        # the whole table into dashes, hiding the comparison the configs that
        # did run can still support. Such configs are named below but left out
        # of the matched set.
        scored = {name: run for name, run in answers.items() if run["items"]}
        unstarted = [name for name, run in answers.items() if not run["items"]]
        common = set.intersection(*({i["id"] for i in run["items"]} for run in scored.values())) if scored else set()
        matched = {
            name: {"summary": summarize_answers([i for i in run["items"] if i["id"] in common])}
            for name, run in scored.items()
        }
        a = lambda key: (lambda r: r["summary"]["answerable"][key])
        note = "Partial runs (Groq daily token cap): " + ", ".join(
            f"{n} answered {len(r['items'])}/40, {len(r['skipped_uncached'])} not generated" for n, r in partial.items()
        ) + "."
        if unstarted:
            note += " No answers at all, so excluded from the matched set: " + ", ".join(unstarted) + "."
        if not common:
            lines += ["", "### Answers on the matched subset", "", note,
                      " The configs with answers share no common items, so no matched comparison is possible.", ""]
        else:
            lines += ["", f"### Answers on the matched subset ({len(common)} items: {', '.join(sorted(common))})", "",
                      note + " Every config below is scored on the same items.", ""]
            lines += _table(matched, [
                ("Fact coverage", a("fact_coverage"), "pct"),
                ("Fully correct (all facts)", a("fully_correct_rate"), "pct"),
                ("False refusal", a("false_refusal_rate"), "pct"),
                ("Citation precision", a("citation_precision"), "pct"),
                ("Citation recall", a("citation_recall"), "pct"),
                ("Grounded sentence share", a("grounded_share"), "pct"),
            ])

    out = results_dir / "comparison.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out
